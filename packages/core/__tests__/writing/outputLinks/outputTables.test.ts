// Tests reading linked tables (CSV quoting and delimiters, TSV, JSON shapes, caps) and their LaTeX and Typst copies with rounding and escaping.
import { MAX_TABLE_COLUMNS, MAX_TABLE_ROWS, detectDelimiter, parseOutputTable, readOutputTableCopy, renderOutputTable } from "../../../src/writing/outputLinks/index";

describe("parseOutputTable", () => {
  it("reads RFC 4180 quoting: delimiters, line breaks and doubled quotes inside quotes", () => {
    const table = parseOutputTable("t.csv", 'name,note\r\n"a, b","say ""hi""\nthere"\n\nc,d\n');
    expect(table).toEqual({ header: ["name", "note"], rows: [["a, b", 'say "hi"\nthere'], ["c", "d"]] });
  });

  it("detects tab, then semicolon, then comma", () => {
    expect(detectDelimiter("a\tb,c\n")).toBe("\t");
    expect(detectDelimiter("a;b;c,d\n")).toBe(";");
    expect(detectDelimiter("a,b;c\n")).toBe(",");
    expect(parseOutputTable("t.tsv", "a b\tc\n1\t2").rows).toEqual([["1", "2"]]);
  });

  it("reads JSON as objects (header in first-object order, union appended), arrays, or {columns, rows}", () => {
    expect(parseOutputTable("t.json", '[{"b":1,"a":2},{"c":3}]')).toEqual({ header: ["b", "a", "c"], rows: [[1, 2, ""], ["", "", 3]] });
    expect(parseOutputTable("t.json", '[["x","y"],[1,2]]')).toEqual({ header: ["x", "y"], rows: [[1, 2]] });
    expect(parseOutputTable("t.json", '{"columns":["x"],"rows":[[1],[2]]}').rows).toEqual([[1], [2]]);
    expect(() => parseOutputTable("t.json", '{"a":1}')).toThrow(/array of objects/);
  });

  it("refuses tables over the caps", () => {
    expect(() => parseOutputTable("t.csv", `${Array.from({ length: MAX_TABLE_COLUMNS + 1 }, (_, i) => `c${i}`).join(",")}\n`)).toThrow(/columns/);
    expect(() => parseOutputTable("t.csv", `h\n${"1\n".repeat(MAX_TABLE_ROWS + 1)}`)).toThrow(/rows/);
  });
});

describe("renderOutputTable", () => {
  const table = parseOutputTable("r/t.csv", "model,acc\nA_1 & co,0.91234\nB,1.5\n");

  it("writes a booktabs tabular with numeric columns right-aligned, rounded and escaped", () => {
    expect(renderOutputTable(table, { source: "exp", path: "r/t.csv", decimals: 2 }, "latex")).toBe([
      "% Generated by LabShelf from exp:r/t.csv. Edits are overwritten.", "\\begin{tabular}{lr}", "\\toprule", "model & acc \\\\", "\\midrule",
      "A\\_1 \\& co & 0.91 \\\\", "B & 1.50 \\\\", "\\bottomrule", "\\end{tabular}", "",
    ].join("\n"));
  });

  it("rounds fractions only, keeps scientific notation and never prints -0", () => {
    const counts = parseOutputTable("t.csv", "n,p,d\n52,2.65649610544227e-21,-0.0004\n197,0.00367710350883624,1.25\n");
    const text = renderOutputTable(counts, { source: "exp", path: "t.csv", decimals: 2 }, "latex");
    expect(text).toContain("\\begin{tabular}{rrr}");
    expect(text).toContain("52 & 2.66e-21 & 0.00 \\\\");
    expect(text).toContain("197 & 0.00 & 1.25 \\\\");
  });

  it("keeps numbers as written without decimals", () => {
    expect(renderOutputTable(table, { source: "exp", path: "r/t.csv" }, "latex")).toContain("0.91234 \\\\");
  });

  it("writes a Typst table with escaped content", () => {
    const text = renderOutputTable(parseOutputTable("t.csv", "a,b\n#x [y],2\n"), { source: "exp", path: "t.csv" }, "typst");
    expect(text).toContain("  columns: 2,\n  align: (left, right),\n  table.header([a], [b]),\n  [\\#x \\[y\\]], [2],\n)");
  });

  it("reads its own copies back for a preview", () => {
    expect(readOutputTableCopy(renderOutputTable(table, { source: "e", path: "t.csv" }, "latex"), "latex")).toEqual([["model", "acc"], ["A_1 & co", "0.91234"], ["B", "1.5"]]);
    expect(readOutputTableCopy(renderOutputTable(table, { source: "e", path: "t.csv" }, "typst"), "typst")).toEqual([["model", "acc"], ["A_1 & co", "0.91234"], ["B", "1.5"]]);
  });
});
