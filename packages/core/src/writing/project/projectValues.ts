import type { ProjectSettings } from "./projectFile.js";

const MODULE = "writing/projectValue";

// --- JSON leaves ---

export type LeafProjectValue = number | string | boolean;

export interface ProjectValueLeaf {
  /** `<file name without .json>.<dotted path>`: what `\lsvalue` takes. */
  key: string;
  value: LeafProjectValue;
  /** The JSON file as listed under `values:`, relative to the project folder. */
  file: string;
  /** Dotted path of the leaf inside the file. */
  path: string;
}

export interface ProjectValueSource {
  folder: string;
  settings: ProjectSettings;
  /** Main file relative to the folder; undefined when the project has none yet. */
  main: string | undefined;
}

export interface FlattenedProjectValues {
  leaves: ProjectValueLeaf[];
  /** Keys of leaves left out because the key has a character a LaTeX control sequence name cannot carry. */
  skipped: string[];
}

const KEY_CHARACTERS = /^[A-Za-z0-9._-]+$/;

/** The key prefix of a value file: its name without `.json`. */
const deriveProjectValueFileBase = (file: string): string => file.replace(/^.*\//, "").replace(/\.json$/i, "");

function isLeaf(node: unknown): node is LeafProjectValue {
  return typeof node === "number" || typeof node === "string" || typeof node === "boolean";
}

/** Leaves in document order; `null` is skipped, array items are numbered from 0. */
export function deriveProjectValueLeaves(file: string, json: unknown): FlattenedProjectValues {
  const base = deriveProjectValueFileBase(file);
  const leaves: ProjectValueLeaf[] = [];
  const skipped: string[] = [];
  const visit = (node: unknown, path: string): void => {
    if (isLeaf(node)) {
      const key = `${base}.${path}`;
      if (KEY_CHARACTERS.test(key)) { leaves.push({ key, value: node, file, path }); } else { skipped.push(key); }
      return;
    }
    if (node === null || typeof node !== "object") { return; }
    const children = Array.isArray(node) ? node.map((item, index): [string, unknown] => [String(index), item]) : Object.entries(node);
    for (const [name, child] of children) { visit(child, path === "" ? name : `${path}.${name}`); }
  };
  // A file whose root is a single value has no path to name it by.
  if (json !== null && typeof json === "object") { visit(json, ""); }
  return { leaves, skipped };
}

// --- Members of a value file ---

export interface ProjectValueMember {
  name: string;
  /** The value itself when the member is a leaf; undefined when it holds more members. */
  leaf: ProjectValueLeaf | undefined;
}

/** Members of `parent` (dotted, "" for the root) in `file`; array indexes are left out because Typst reads them with `.at()`. */
export function deriveProjectValueMembers(leaves: readonly ProjectValueLeaf[], file: string, parent: string): ProjectValueMember[] {
  const prefix = parent === "" ? "" : `${parent}.`;
  const members = new Map<string, ProjectValueLeaf | undefined>();
  for (const leaf of leaves) {
    if (leaf.file !== file || !leaf.path.startsWith(prefix)) { continue; }
    const rest = leaf.path.slice(prefix.length);
    const dot = rest.indexOf(".");
    const name = dot < 0 ? rest : rest.slice(0, dot);
    if (!/^\d+$/.test(name)) { members.set(name, dot < 0 ? leaf : undefined); }
  }
  return [...members].map(([name, leaf]) => ({ name, leaf }));
}

// --- The generated values file ---

export const VALUES_FILE_NAME = "labshelf-values.tex";
export const VALUES_HEADER = "% Generated by LabShelf from the JSON files listed under values in labshelf.yaml. Edits are overwritten.";

// PLATFORM: \csname builds the name from character codes, so the `@` needs no \makeatletter.
const LSVALUE_MACRO = String.raw`\providecommand{\lsvalue}[1]{\ifcsname lsv@#1\endcsname\csname lsv@#1\endcsname\else ??\PackageWarning{labshelf}{Unknown value #1}\fi}`;

const ESCAPES: Record<string, string> = {
  "\\": String.raw`\textbackslash{}`, "{": String.raw`\{`, "}": String.raw`\}`, "$": String.raw`\$`, "&": String.raw`\&`,
  "#": String.raw`\#`, "_": String.raw`\_`, "%": String.raw`\%`, "~": String.raw`\textasciitilde{}`, "^": String.raw`\textasciicircum{}`,
};

/** Text that LaTeX prints as written; line breaks become spaces because a macro body cannot hold a paragraph break. */
export function escapeLatex(text: string): string {
  return text.replace(/[\\{}$&#_%~^]/g, (character) => ESCAPES[character]!).replace(/\r\n|\r|\n/g, " ");
}

/** The same leaves always give the same bytes: the macro, then one definition per leaf in the order given, LF line ends. */
export function createProjectValueFile(leaves: readonly ProjectValueLeaf[]): string {
  const definitions = leaves.map((leaf) => `\\expandafter\\def\\csname lsv@${leaf.key}\\endcsname{${escapeLatex(String(leaf.value))}}`);
  return [VALUES_HEADER, LSVALUE_MACRO, ...definitions].join("\n") + "\n";
}

/** A file path as `values:` lists it, with "/" separators and no `./`, as leaves name their file. */
export const deriveProjectValueFilePath = (listed: string): string => posixPathOps.resolve(listed.replaceAll("\\", "/"));

// --- The main file's input line ---

export type ProjectValueInputResult =
  | { kind: "present" | "added"; text: string }
  /** Without `\begin{document}` the file is a fragment; the text is returned as it was. */
  | { kind: "no-document"; text: string };

const INPUT_LINE = String.raw`\input{labshelf-values}`;
const LOADS_VALUES = /^[^%\n]*\\input\{(?:[^}]*\/)?labshelf-values(?:\.tex)?\}/m;

function documentStart(text: string): number | undefined {
  for (const match of text.matchAll(/\\begin\{document\}/g)) {
    const lineStart = text.lastIndexOf("\n", match.index - 1) + 1;
    // TRAP: a `%` escaped as `\%` is text, not a comment.
    if (!/(?<!\\)%/.test(text.slice(lineStart, match.index))) { return match.index; }
  }
  return undefined;
}

/** The main file's text with the values file loaded before `\begin{document}`. */
export function withProjectValueInput(text: string): ProjectValueInputResult {
  if (LOADS_VALUES.test(text)) { return { kind: "present", text }; }
  const start = documentStart(text);
  if (start === undefined) { return { kind: "no-document", text }; }
  return { kind: "added", text: `${text.slice(0, start)}${INPUT_LINE}\n${text.slice(start)}` };
}

// --- Reading the listed value files ---

/** Leaves of every readable value file, in the order the files are listed; a missing or invalid file, or one whose name an earlier file already took, is logged and skipped. */
export async function readProjectValues(project: Pick<ProjectValueSource, "folder" | "settings">, { fs, paths, logger }: ProjectReadContext): Promise<ProjectValueLeaf[]> {
  const leaves: ProjectValueLeaf[] = [];
  const bases = new Set<string>();
  for (const listed of project.settings.values ?? []) {
    const file = deriveProjectValueFilePath(listed);
    const context = { project: project.settings.id, file };
    if (bases.has(deriveProjectValueFileBase(file))) {
      await logger.log("WARN", MODULE, "value file skipped: an earlier file has the same name", context);
      continue;
    }
    bases.add(deriveProjectValueFileBase(file));
    let json: unknown;
    try {
      json = JSON.parse(await fs.readText(paths.join(project.folder, file)));
    } catch (error) {
      await logger.log("WARN", MODULE, "value file skipped", { ...context, reason: formatError(error) });
      continue;
    }
    const flat = deriveProjectValueLeaves(file, json);
    if (flat.skipped.length > 0) {
      await logger.log("WARN", MODULE, "value keys skipped: only letters, digits, '.', '-' and '_' are allowed", { ...context, keys: flat.skipped });
    }
    leaves.push(...flat.leaves);
  }
  return leaves;
}

// --- LaTeX references ---

export interface LatexProjectValueReference {
  key: string;
  /** Character offsets of the key in the text. */
  start: number;
  end: number;
}

const OPEN_LSVALUE = /\\lsvalue\{([^{}\s]*)$/;
const LSVALUE = /\\lsvalue\{([^{}\s]*)\}/g;

/** Column where the partial key before the cursor starts, or undefined when the cursor is not inside `\lsvalue{`. */
export function findLatexProjectValueStart(linePrefix: string): number | undefined {
  const open = OPEN_LSVALUE.exec(linePrefix);
  return open ? open.index + open[0].length - open[1]!.length : undefined;
}

/** The `\lsvalue{key}` whose key contains the offset. */
export function findLatexProjectValue(text: string, offset: number): LatexProjectValueReference | undefined {
  for (const match of text.matchAll(LSVALUE)) {
    const key = match[1]!;
    const start = match.index + match[0].length - 1 - key.length;
    if (start <= offset && offset <= start + key.length) { return { key, start, end: start + key.length }; }
  }
  return undefined;
}

// --- Typst references ---

export interface TypstProjectValuePrefix {
  /** The `json()` path literal as written. */
  source: string;
  /** Complete member names before the one being typed, dot-joined; "" when there are none. */
  parent: string;
  /** Character offset where the member being typed starts. */
  start: number;
}

export interface TypstProjectValueReference {
  source: string;
  /** Dot-joined members from the file root up to and including the one under the cursor. */
  path: string;
  /** Character offsets of that last member. */
  start: number;
  end: number;
}

interface Member { name: string; start: number; end: number }
interface Chain { source: string; members: Member[]; end: number }

const NAME = String.raw`[\p{L}_][\p{L}\p{N}_-]*`;
const BINDING = new RegExp(String.raw`\blet\s+(${NAME})\s*=\s*json\(\s*"([^"\n]*)"\s*\)`, "gu");
const MEMBER_CHARACTERS = String.raw`[\p{L}\p{N}_-]*`;
// A member access that starts a chain is not itself a chain: `a.r.b` does not read the name `r`.
const CHAIN = new RegExp(
  String.raw`(?<![\p{L}\p{N}_.-])(?:json\(\s*"([^"\n]*)"\s*\)|(${NAME}))((?:\.${MEMBER_CHARACTERS})*)`, "gu",
);

function memberList(text: string, from: number): Member[] {
  return [...text.matchAll(new RegExp(String.raw`\.(${MEMBER_CHARACTERS})`, "gu"))].map((match) => {
    const start = from + match.index + 1;
    return { name: match[1]!, start, end: start + match[1]!.length };
  });
}

/** Every `json("…").a.b` and `name.a.b` in the text; a name counts when a `let` binds it to json() earlier. */
function chains(text: string): Chain[] {
  const bindings = [...text.matchAll(BINDING)].map((match) => ({ name: match[1]!, source: match[2]!, at: match.index }));
  const found: Chain[] = [];
  for (const match of text.matchAll(CHAIN)) {
    const source = match[1] ?? bindings.filter((binding) => binding.name === match[2] && binding.at < match.index).at(-1)?.source;
    if (source === undefined) { continue; }
    const end = match.index + match[0].length;
    found.push({ source, members: memberList(match[3]!, end - match[3]!.length), end });
  }
  return found;
}

/** What is being typed after `json("…").` or `name.`, from the text up to the cursor. */
export function findTypstProjectValuePrefix(text: string, offset: number): TypstProjectValuePrefix | undefined {
  const chain = chains(text.slice(0, offset)).find((candidate) => candidate.end === offset && candidate.members.length > 0);
  const typing = chain?.members.at(-1);
  if (!chain || !typing) { return undefined; }
  return { source: chain.source, parent: chain.members.slice(0, -1).map((member) => member.name).join("."), start: typing.start };
}

/** The member path whose last name contains the offset. */
export function findTypstProjectValue(text: string, offset: number): TypstProjectValueReference | undefined {
  for (const chain of chains(text)) {
    const index = chain.members.findIndex((member) => member.start <= offset && offset <= member.end);
    const member = chain.members[index];
    if (member && member.name !== "") {
      const path = chain.members.slice(0, index + 1).map((part) => part.name).join(".");
      return { source: chain.source, path, start: member.start, end: member.end };
    }
  }
  return undefined;
}
