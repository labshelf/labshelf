/** Builds the text of a project's generated labshelf.bib from the library papers it cites. */
// CONTRACT: documents/contracts/library-format.md#labshelfbib

import { bibtexEntry } from "../../import/bibtex/index.js";
import type { PaperRecord } from "../../model/index.js";

export const BIBLIOGRAPHY_HEADER = "% Generated by LabShelf from the library papers this project cites. Edits are overwritten.";

export interface GeneratedBibliography {
  text: string;
  /** Cited keys with an entry in the file, sorted. */
  resolved: string[];
  /** Cited keys no library paper has; they are left to the user's own .bib files. */
  missing: string[];
}

function byCiteKey(papers: readonly PaperRecord[]): Map<string, PaperRecord> {
  const byKey = new Map<string, PaperRecord>();
  // INVARIANT: on a duplicate cite key the paper with the smallest id wins, so the output does not depend on scan order.
  const ordered = [...papers].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  for (const paper of ordered) { if (!byKey.has(paper.citeKey)) { byKey.set(paper.citeKey, paper); } }
  return byKey;
}

/** The same keys and papers always give the same bytes: entries in key order, no file paths, LF line ends. */
export function generateBibliography(keys: readonly string[], papers: readonly PaperRecord[]): GeneratedBibliography {
  const library = byCiteKey(papers);
  const sorted = [...new Set(keys)].sort();
  const resolved = sorted.filter((key) => library.has(key));
  const missing = sorted.filter((key) => !library.has(key));
  // BibTeX keys are case-sensitive, so `Smith2020` and `smith2020` are different citations.
  const entries = resolved.map((key) => bibtexEntry(library.get(key)!, { includeFile: false }));
  const text = [BIBLIOGRAPHY_HEADER, ...entries].join("\n\n") + "\n";
  return { text, resolved, missing };
}
