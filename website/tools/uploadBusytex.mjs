// Uploads the browser LaTeX engine (texlyre-busytex, AGPL-3.0) to the labshelf-assets R2 bucket, where the website Worker serves it at
// /busytex/<version>/<file>, and writes src/open/runtimes/busytexManifest.ts with each file's SHA-256 and size.
// Usage: node website/tools/uploadBusytex.mjs [--tarball <busytex-assets.tar.gz>] [--dry-run]
// Without --tarball it downloads the pinned release; --dry-run extracts, hashes and writes the manifest without uploading.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream, createWriteStream } from "node:fs";
import { mkdtemp, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const VERSION = "1.4.1";
const RELEASE_URL = `https://github.com/TeXlyre/texlyre-busytex/releases/download/assets-v${VERSION}/busytex-assets.tar.gz`;
const BUCKET = "labshelf-assets";
const FILES = [
  // The combined engine and its Worker scripts.
  "busytex.js", "busytex.wasm", "busytex_worker.js", "busytex_pipeline.js", "busytex_biber.js",
  // TeX Live basic, preloaded.
  "texlive-basic.js", "texlive-basic.data", "texlive-basic.js.providespackage.txt",
  // TeX Live recommended, loaded on demand (booktabs and most common packages live only here).
  "texlive-recommended.js", "texlive-recommended.data", "texlive-recommended.js.providespackage.txt",
  // Biber, for biblatex.
  "biber.js", "biber.wasm", "biber.data",
];
const CONTENT_TYPES = { wasm: "application/wasm", js: "text/javascript; charset=utf-8", data: "application/octet-stream", txt: "text/plain; charset=utf-8" };

const website = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(website, "src/open/runtimes/busytexManifest.ts");

function parseArgs(argv) {
  const args = { tarball: undefined, dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--dry-run") { args.dryRun = true; }
    else if (argv[i] === "--tarball" && argv[i + 1]) { args.tarball = argv[++i]; }
    else {
      console.error("Usage: node uploadBusytex.mjs [--tarball <busytex-assets.tar.gz>] [--dry-run]");
      process.exit(2);
    }
  }
  return args;
}

async function download(url, path) {
  console.log(`Downloading ${url}`);
  const response = await fetch(url);
  if (!response.ok || !response.body) { throw new Error(`Download failed: HTTP ${response.status}`); }
  await pipeline(Readable.fromWeb(response.body), createWriteStream(path));
}

async function sha256(path) {
  const hash = createHash("sha256");
  await pipeline(createReadStream(path), hash);
  return hash.digest("hex");
}

const contentType = (file) => CONTENT_TYPES[file.slice(file.lastIndexOf(".") + 1)];

function manifestSource(entries) {
  const lines = entries.map(([file, { sha256: digest, bytes }]) => `  "${file}": { sha256: "${digest}", bytes: ${bytes} },`);
  return [
    "// Generated by website/tools/uploadBusytex.mjs; do not edit. The texlyre-busytex files in the labshelf-assets R2 bucket,",
    `// served by the website Worker at /busytex/${VERSION}/<file>.`,
    "",
    `export const BUSYTEX_VERSION = "${VERSION}";`,
    "",
    "/**",
    " * Each uploaded file's SHA-256 (hex) and size in bytes, to audit the bucket against the release.",
    " * @public",
    " */",
    "export const BUSYTEX_FILES: Readonly<Record<string, { sha256: string; bytes: number }>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

const args = parseArgs(process.argv.slice(2));
const work = await mkdtemp(join(tmpdir(), "busytex-"));
try {
  const tarball = args.tarball ?? join(work, "busytex-assets.tar.gz");
  if (!args.tarball) { await download(RELEASE_URL, tarball); }
  const extracted = join(work, "extracted");
  execFileSync("mkdir", ["-p", extracted]);
  execFileSync("tar", ["-xzf", tarball, "-C", extracted, ...FILES.map((file) => `busytex/${file}`)], { stdio: "inherit" });
  const entries = [];
  for (const file of FILES) {
    const path = join(extracted, "busytex", file);
    entries.push([file, { sha256: await sha256(path), bytes: (await stat(path)).size }]);
  }
  for (const [file, { bytes }] of entries) {
    const key = `${BUCKET}/busytex/${VERSION}/${file}`;
    const command = ["wrangler", "r2", "object", "put", key, "--file", join(extracted, "busytex", file), "--content-type", contentType(file), "--remote"];
    if (args.dryRun) { console.log(`[dry run] npx ${command.join(" ")}  (${bytes} bytes)`); continue; }
    console.log(`Uploading ${file} (${bytes} bytes)`);
    execFileSync("npx", command, { cwd: website, stdio: "inherit" });
  }
  await writeFile(manifestPath, manifestSource(entries));
  console.log(`Wrote ${manifestPath}`);
} finally {
  await rm(work, { recursive: true, force: true });
}
