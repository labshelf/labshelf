export function icon(name) {
  if (name === "brand") {
    return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"><path d="M8 5 16 12 8 19"/></svg>';
  }
  if (FILL[name]) {
    return `<svg viewBox="0 0 16 16" fill="currentColor" aria-hidden="true" focusable="false">${FILL[name]}</svg>`;
  }
  return `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${STROKE[name] ?? ""}</svg>`;
}

/** Replace every `<span data-icon="name">` placeholder with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    el.outerHTML = icon(el.dataset.icon);
  }
}
